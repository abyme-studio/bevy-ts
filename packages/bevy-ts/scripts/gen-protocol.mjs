// Generates `protocol.d.ts` (exported as `bevy-ts/protocol`) from protocol/bevy-ts.openrpc.json.
import { compile } from "json-schema-to-typescript";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const doc = JSON.parse(readFileSync(here("../../../protocol/bevy-ts.openrpc.json"), "utf8"));

const rewrite = (v) => {
  if (Array.isArray(v)) return v.map(rewrite);
  if (v && typeof v === "object") {
    const o = {};
    for (const [k, x] of Object.entries(v)) o[k] = k === "$ref" ? x.replace("#/components/schemas/", "#/definitions/") : rewrite(x);
    return o;
  }
  return v;
};

const definitions = rewrite(doc.components.schemas);
for (const [name, s] of Object.entries(definitions)) s.title = name;

const types = await compile({ title: "ProtocolTypes", type: "object", definitions, additionalProperties: false }, "ProtocolTypes", {
  bannerComment: "",
  unreachableDefinitions: true,
  declareExternallyReferenced: true,
  additionalProperties: false,
  style: { printWidth: 120 },
  format: true,
});

const tsOf = (schema) => {
  if (!schema || Object.keys(schema).length === 0) return "unknown";
  if (schema.$ref) return schema.$ref.split("/").pop();
  if (schema.type === "null") return "null";
  return "unknown";
};

const methods = doc.methods
  .map((m) => {
    const params = m.params.length ? tsOf(m.params[0].schema) + (m.params[0].required ? "" : " | undefined") : "undefined";
    return `  ${JSON.stringify(m.name)}: { params: ${params}; result: ${tsOf(m.result.schema)}; crate: ${JSON.stringify(m["x-bevy-ts-crate"])}; watch: ${!!m["x-bevy-ts-watch"]} };`;
  })
  .join("\n");

const out = `// @generated by packages/bevy-ts/scripts/gen-protocol.mjs from protocol/bevy-ts.openrpc.json. Do not edit.

/** The protocol version these types describe. */
export const PROTOCOL_VERSION: ${JSON.stringify(doc.info.version)};

${types.replace(/export interface ProtocolTypes \{\}\n?/, "")}
/** Every method: params, result, owning crate, and whether it streams. */
export interface Methods {
${methods}
}

export type MethodName = keyof Methods;
`;
writeFileSync(here("../protocol.d.ts"), out);
console.error("wrote packages/bevy-ts/protocol.d.ts");
