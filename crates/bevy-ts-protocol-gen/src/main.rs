//! Generates the Rust protocol types from `protocol/bevy-ts.openrpc.json`.
//!
//! `cargo run -p bevy-ts-protocol-gen` writes `crates/bevy-ts-remote/src/protocol.rs`. The TS
//! half comes from `packages/bevy-ts/scripts/gen-protocol.mjs`; `scripts/gen-protocol.sh`
//! runs both, and with `--check` fails when the output differs from what is checked in.

use serde_json::{Value, json};
use std::path::{Path, PathBuf};

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..").canonicalize().unwrap()
}

/// Rewrites `#/components/schemas/X` refs to `#/definitions/X`.
fn rewrite_refs(v: &mut Value) {
    match v {
        Value::Object(o) => {
            if let Some(Value::String(r)) = o.get_mut("$ref") {
                *r = r.replace("#/components/schemas/", "#/definitions/");
            }
            o.values_mut().for_each(rewrite_refs);
        }
        Value::Array(a) => a.iter_mut().for_each(rewrite_refs),
        _ => {}
    }
}

/// The Rust source for a document.
pub fn generate(doc: &Value) -> String {
    let mut defs = doc["components"]["schemas"].clone();
    rewrite_refs(&mut defs);
    let root: schemars::schema::RootSchema =
        serde_json::from_value(json!({ "$schema": "http://json-schema.org/draft-07/schema#", "definitions": defs }))
            .expect("schemas parse");
    let mut space = typify::TypeSpace::new(typify::TypeSpaceSettings::default().with_struct_builder(false));
    space.add_root_schema(root).expect("typify accepts the schemas");
    let types = prettyplease::unparse(&syn::parse2::<syn::File>(space.to_stream()).expect("typify emits valid Rust"));

    let mut methods = String::new();
    let mut channel = String::new();
    for m in doc["methods"].as_array().unwrap() {
        if let Some(side) = m["x-bevy-ts-channel"].as_str() {
            channel.push_str(&format!("    ({:?}, {:?}),\n", m["name"].as_str().unwrap(), side));
            continue;
        }
        methods.push_str(&format!(
            "    Method {{ name: {:?}, crate_name: {:?}, watch: {} }},\n",
            m["name"].as_str().unwrap(),
            m["x-bevy-ts-crate"].as_str().expect("every method names its crate"),
            m["x-bevy-ts-watch"].as_bool().unwrap_or(false),
        ));
    }
    format!(
        "// @generated by bevy-ts-protocol-gen from protocol/bevy-ts.openrpc.json. Do not edit.\n\
         #![allow(clippy::all, clippy::pedantic, dead_code, missing_docs, unused_imports)]\n\n\
         /// The protocol version this build speaks.\n\
         pub const VERSION: &str = {version:?};\n\n\
         /// One method of the contract.\n\
         #[derive(Clone, Copy, Debug, PartialEq, Eq)]\n\
         pub struct Method {{\n    pub name: &'static str,\n    /// The crate whose plugin serves it.\n    pub crate_name: &'static str,\n    pub watch: bool,\n}}\n\n\
         /// Every method in the contract.\n\
         pub const METHODS: &[Method] = &[\n{methods}];\n\n\
         /// Notifications on a viewport's Mach channel, as (method, the side that sends it).\n\
         pub const CHANNEL: &[(&str, &str)] = &[\n{channel}];\n\n{types}",
        version = doc["info"]["version"].as_str().unwrap(),
    )
}

/// Writes `src` to `path` only when its bytes differ, so a check that changes nothing leaves the
/// file's mtime, and the crates built from it, alone. Whether it wrote.
fn write_if_changed(path: &std::path::Path, src: &str) -> bool {
    if std::fs::read(path).is_ok_and(|old| old == src.as_bytes()) {
        return false;
    }
    std::fs::write(path, src).unwrap();
    true
}

fn main() {
    let root = root();
    let doc: Value = serde_json::from_str(&std::fs::read_to_string(root.join("protocol/bevy-ts.openrpc.json")).unwrap()).unwrap();
    let out = root.join("crates/bevy-ts-remote/src/protocol.rs");
    if write_if_changed(&out, &generate(&doc)) {
        eprintln!("wrote {}", out.display());
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_same_bytes_are_not_written_again() {
        let dir = std::env::temp_dir().join(format!("protocol-gen-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.join("protocol.rs");
        assert!(write_if_changed(&path, "a"));
        let mtime = || std::fs::metadata(&path).unwrap().modified().unwrap();
        let before = mtime();
        std::thread::sleep(std::time::Duration::from_millis(20));
        assert!(!write_if_changed(&path, "a"));
        assert_eq!(mtime(), before);
        assert!(write_if_changed(&path, "b"));
        assert_eq!(std::fs::read_to_string(&path).unwrap(), "b");
        std::fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn methods_of_feature_crates_come_out_of_the_same_run() {
        let doc = json!({
            "openrpc": "1.3.2",
            "info": { "version": "1.1.0" },
            "methods": [
                { "name": "bevy-ts/hello", "x-bevy-ts-crate": "bevy-ts-remote", "params": [], "result": { "name": "r", "schema": {} } },
                { "name": "bevy-ts/example_method", "x-bevy-ts-crate": "bevy-ts-example", "params": [],
                  "result": { "name": "r", "schema": { "$ref": "#/components/schemas/ExampleResult" } } }
            ],
            "components": { "schemas": { "ExampleResult": { "type": "object", "required": ["ok"], "properties": { "ok": { "type": "boolean" } } } } }
        });
        let src = generate(&doc);
        assert!(src.contains("name: \"bevy-ts/example_method\", crate_name: \"bevy-ts-example\""));
        assert!(src.contains("pub struct ExampleResult"));
        assert!(src.contains("pub const VERSION: &str = \"1.1.0\""));
    }

    #[test]
    fn channel_messages_are_listed_apart_from_methods() {
        let doc = json!({
            "openrpc": "1.3.2",
            "info": { "version": "1.1.0" },
            "methods": [
                { "name": "frame", "x-bevy-ts-crate": "bevy-ts-viewport", "x-bevy-ts-channel": "engine", "params": [] }
            ],
            "components": { "schemas": {} }
        });
        let src = generate(&doc);
        assert!(src.contains("(\"frame\", \"engine\")"));
        assert!(!src.contains("Method { name: \"frame\""));
    }
}
